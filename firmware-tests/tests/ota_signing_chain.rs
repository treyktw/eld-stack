//! End-to-end: a manifest signed by `tools/sign-manifest.sh` must verify
//! against the public key compiled into the firmware.
//!
//! This is the test that stops the worst failure in the whole update path. If
//! the shell script and `canonical_message()` ever disagree about which bytes
//! are signed — an added field, a reordering, a stray newline — every device
//! rejects every update. That is a fleet-wide outage with no remote fix,
//! because the fix would itself need to be signed.
//!
//! The fixture below was produced by the real script with the TEST key whose
//! public half is compiled into `firmware/src/ota/key.rs` (the private half
//! was generated by `scripts/gen-ota-key.sh` and never committed):
//!
//! ```text
//! head -c 4096 /dev/urandom > fw.bin
//! ./firmware/tools/sign-manifest.sh ota-test.pem \
//!     0.1.8 fw.bin https://updates.example.com/firmware/0.1.8.bin
//! ```
//!
//! Regenerate it the same way if the manifest format changes deliberately.
//! Nothing secret is committed here: the signature and the public key are both
//! public by design, and the private key never leaves the operator's machine.

use ed25519_dalek::{Signature, Verifier as DalekVerifier, VerifyingKey};
use eld_decoders_test::ota::key::{resolve, KeySource, BUILD_TIME_PUBLIC_KEY, PUBLIC_KEY_LEN};
use eld_decoders_test::ota::manifest::parse;
use eld_decoders_test::ota::signature::{verify_manifest, SignatureError, Verifier, SIGNATURE_LEN};

/// Produced by tools/sign-manifest.sh. See the module docs.
const SIGNED_MANIFEST: &str = r#"{"version":"0.1.8","url":"https://updates.example.com/firmware/0.1.8.bin","sha256":"1c0c991b41b4c49417d7b41ea2378fc41325bf8ea092bbce92d3fca7e223fd4f","size":4096,"required":false,"sig":"NS4a3zUdhxqvoiCkECjWIYOs078hn57t71LfpypBFWqtkT2f1zI1M5bcxFOZC83zXGSmwz1ky1bGap4AkT6CBA=="}"#;

struct Ed25519;

impl Verifier for Ed25519 {
    fn verify(
        &self,
        message: &[u8],
        signature: &[u8; SIGNATURE_LEN],
        public_key: &[u8; PUBLIC_KEY_LEN],
    ) -> bool {
        let Ok(key) = VerifyingKey::from_bytes(public_key) else {
            return false;
        };
        key.verify(message, &Signature::from_bytes(signature))
            .is_ok()
    }
}

#[test]
fn the_build_server_and_the_device_agree_on_what_is_signed() {
    let manifest = parse(SIGNED_MANIFEST).expect("script output must parse");
    assert_eq!(
        verify_manifest(&Ed25519, SIGNED_MANIFEST, &manifest, &BUILD_TIME_PUBLIC_KEY),
        Ok(()),
        "sign-manifest.sh and canonical_message() have diverged — every device \
         would reject every update"
    );
}

#[test]
fn a_key_is_actually_provisioned() {
    // Guards the state this change existed to leave behind: before the keypair
    // was generated, resolve() returned NotConfigured and the device installed
    // nothing.
    assert_ne!(
        BUILD_TIME_PUBLIC_KEY, [0u8; PUBLIC_KEY_LEN],
        "no signing key compiled in — updates would be refused"
    );

    let trusted = resolve(None).expect("a build-time key should resolve");
    assert_eq!(trusted.source, KeySource::BuildTime);
    assert_eq!(trusted.key, BUILD_TIME_PUBLIC_KEY);
}

#[test]
fn tampering_with_the_signed_document_is_caught() {
    // Same signature, one byte of the digest changed: the image has been
    // swapped for a different one.
    let tampered = SIGNED_MANIFEST.replace(
        "1c0c991b41b4c49417d7b41ea2378fc41325bf8ea092bbce92d3fca7e223fd4f",
        "1c0c991b41b4c49417d7b41ea2378fc41325bf8ea092bbce92d3fca7e223fd4a",
    );
    let manifest = parse(&tampered).expect("still parses");
    assert_eq!(
        verify_manifest(&Ed25519, &tampered, &manifest, &BUILD_TIME_PUBLIC_KEY),
        Err(SignatureError::Invalid)
    );
}

#[test]
fn the_signature_does_not_verify_under_a_different_key() {
    let mut wrong = BUILD_TIME_PUBLIC_KEY;
    wrong[0] ^= 0xff;
    let manifest = parse(SIGNED_MANIFEST).unwrap();
    assert_eq!(
        verify_manifest(&Ed25519, SIGNED_MANIFEST, &manifest, &wrong),
        Err(SignatureError::Invalid)
    );
}
