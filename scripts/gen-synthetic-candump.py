#!/usr/bin/env python3
"""Generate a synthetic `candump -L` log for the can-replay demo.

Everything here is made up: a TEST VIN (valid check digit, fictitious WMI
"TST"), round-number engine values, and a 60-second drive at a steady speed
so the odometer delta and the speed integral can be compared.

    python3 scripts/gen-synthetic-candump.py > firmware-tests/fixtures/synthetic-drive.log
"""

import struct

T0 = 1_780_000_000.0
lines = []


def emit(t, can_id, data, extended=True):
    ident = f"{can_id:08X}" if extended else f"{can_id:03X}"
    lines.append(f"({T0 + t:.6f}) vcan0 {ident}#{bytes(data).hex().upper()}")


def j1939_id(priority, pgn, sa, da=0xFF):
    pf = (pgn >> 8) & 0xFF
    if pf < 0xF0:  # PDU1: PS is a destination address
        pgn = (pgn & 0x3FF00) | da
    return (priority << 26) | (pgn << 8) | sa


def vin_with_check_digit(body16):
    tr = {**{str(i): i for i in range(10)},
          **dict(zip("ABCDEFGH", range(1, 9))), **dict(zip("JKLMN", range(1, 6))),
          "P": 7, "R": 9, **dict(zip("STUVWXYZ", range(2, 10)))}
    w = [8, 7, 6, 5, 4, 3, 2, 10, 0, 9, 8, 7, 6, 5, 4, 3, 2]
    v = body16[:8] + "0" + body16[8:]
    s = sum(tr[c] * w[i] for i, c in enumerate(v)) % 11
    return body16[:8] + ("X" if s == 10 else str(s)) + body16[8:]


ENGINE = 0x00
INSTRUMENT = 0x17
BRAKES = 0x0B

VIN = vin_with_check_digit("TSTDEMX0" + "T" + "0000042")


def bam(t, sa, pgn, payload):
    """Broadcast a >8 byte message via J1939-21 TP.CM BAM + TP.DT."""
    n = (len(payload) + 6) // 7
    cm = [0x20, len(payload) & 0xFF, len(payload) >> 8, n, 0xFF,
          pgn & 0xFF, (pgn >> 8) & 0xFF, (pgn >> 16) & 0xFF]
    emit(t, j1939_id(7, 0xEC00, sa), cm)
    for i in range(n):
        chunk = payload[i * 7:(i + 1) * 7]
        chunk = chunk + bytes([0xFF] * (7 - len(chunk)))
        emit(t + 0.05 * (i + 1), j1939_id(7, 0xEB00, sa), bytes([i + 1]) + chunk)


def dtc(spn, fmi, oc):
    return bytes([spn & 0xFF, (spn >> 8) & 0xFF, ((spn >> 16) & 0x7) << 5 | fmi, oc & 0x7F])


SPEED_KPH = 96.0          # ~59.7 mph, held for the whole drive
ODO_START_KM = 412_345.0  # synthetic
DURATION_S = 60

# VIN and a multi-DTC DM1 over BAM right after key-on.
bam(0.10, ENGINE, 0xFEEC, VIN.encode() + b"*")
bam(0.60, ENGINE, 0xFECA, bytes([0x04, 0xFF]) + dtc(100, 1, 2) + dtc(110, 16, 1) + dtc(520_200, 31, 3))

t = 1.0
while t <= DURATION_S + 1e-9:
    km = ODO_START_KM + SPEED_KPH * (t - 1.0) / 3600.0
    rpm = 1400 + 25 * ((int(t) % 4) - 2)
    # EEC1 (0xF004), SPN 190 at bytes 3..4, 0.125 rpm/bit.
    emit(t, j1939_id(3, 0xF004, ENGINE),
         bytes([0xFF, 0xFF, 0xFF]) + struct.pack("<H", int(rpm / 0.125)) + bytes([0xFF] * 3))
    # CCVS1 (0xFEF1), SPN 84 at bytes 1..2, 1/256 km/h per bit. Every 100 ms.
    for k in range(10):
        emit(t + k * 0.1, j1939_id(6, 0xFEF1, BRAKES),
             bytes([0xFF]) + struct.pack("<H", int(SPEED_KPH * 256)) + bytes([0xFF] * 5))
    if int(t) % 5 == 1:
        # HRVD (0xFEC1), SPN 917, 5 m/bit — the preferred odometer.
        emit(t + 0.02, j1939_id(6, 0xFEC1, INSTRUMENT),
             struct.pack("<I", int(km * 1000 / 5)) + bytes([0xFF] * 4))
        # VD (0xFEE0), SPN 245, 0.125 km/bit — coarse; must not override HRVD.
        emit(t + 0.03, j1939_id(6, 0xFEE0, INSTRUMENT),
             bytes([0xFF] * 4) + struct.pack("<I", int(km / 0.125)))
    if int(t) % 10 == 1:
        # Dash display (0xFEFC), SPN 96 fuel level at byte 1, 0.4 %/bit.
        emit(t + 0.04, j1939_id(6, 0xFEFC, INSTRUMENT), bytes([0xFF, round(72.4 / 0.4)] + [0xFF] * 6))
        # Engine hours (0xFEE5), SPN 247, 0.05 h/bit.
        emit(t + 0.05, j1939_id(6, 0xFEE5, ENGINE), struct.pack("<I", round(18_420.35 / 0.05)) + bytes([0xFF] * 4))
    t += 1.0

# A light-duty ECU on the same capture answering OBD-II Mode 01 (11-bit).
emit(DURATION_S + 0.5, 0x7E8, [0x04, 0x41, 0x0C, 0x1A, 0xF8, 0x00, 0x00, 0x00], extended=False)  # rpm 1726
emit(DURATION_S + 0.6, 0x7E8, [0x03, 0x41, 0x0D, 0x60, 0x00, 0x00, 0x00, 0x00], extended=False)  # 96 km/h
emit(DURATION_S + 0.7, 0x7E8, [0x03, 0x41, 0x05, 0x7B, 0x00, 0x00, 0x00, 0x00], extended=False)  # coolant 83 C

lines.sort(key=lambda l: float(l[1:l.index(")")]))
print("# Synthetic candump -L capture. Generated by scripts/gen-synthetic-candump.py.")
print(f"# Fictitious TEST VIN {VIN}; all values are made up.")
print("\n".join(lines))
